export interface ProjectFile {
  path: string;
  source: string;
  lang: LanguageId;
}

export interface ProjectAnalysis {
  /** Raw findings per file path (rules + taint). */
  findings: Map<string, RawFinding[]>;
  /** Files whose analysis exceeded the per-file budget (reported as gaps). */
  timedOut: string[];
  /** Files whose analysis crashed (reported as gaps instead of aborting the scan). */
  failed: string[];
  /** Families that actually had a rule pack applied. */
  families: Set<string>;
  /** Minified/generated files (very long lines) that were not rule-analyzed. */
  skippedMinified: string[];
  /** Entry points, call graph and components (also used by the MCP server and the AI layer). */
  map: MapIndex;
  facts: Map<string, FileFacts>;
}

export interface AnalyzeOptions {
  /** Routes that are public on purpose (athena.config.json `publicRoutes`). */
  publicRoutes?: string[];
  /** Active, compiled skills whose rules extend the built-in packs. */
  skills?: CompiledSkills;
  /** Scan root; test-path rules are evaluated relative to it. Defaults to the current directory. */
  root?: string;
}

const FILE_BUDGET_MS = 2000;
/** Wall-clock allowance for pattern rules + investigation of one file before taint is skipped. */
const STAGE_BUDGET_MS = 4000;

const VENDORED_PATH = /(?:^|\/)(?:third_party|thirdparty|vendors?|bower_components|node_modules|site-packages)\/|\.min\.\w+$|\.(?:pb|pb\.gw|generated|gen)\.\w+$|_pb2(?:_grpc)?\.py$/i;
const GENERATED_HEADER = /(?:@generated|auto-?generated|code generated|generated by|do not edit)/i;

/** Third-party, generated or minified code is not the project's own: listed as excluded, not analysed. */
export function isVendoredOrGenerated(relPath: string, source: string): boolean {
  if (VENDORED_PATH.test(relPath) || isSkillFixturePath(relPath)) return true;
  const head = source.slice(0, 600).split('\n', 6).join('\n');
  return GENERATED_HEADER.test(head);
}

/** Bundles and minified output: lines of thousands of characters. */
function isMinified(source: string): boolean {
  let longest = 0;
  let run = 0;
  for (let i = 0; i < source.length; i += 1) {
    if (source.charCodeAt(i) === 10) {
      if (run > longest) longest = run;
      run = 0;
    } else run += 1;
  }
  return Math.max(longest, run) > 1500;
}

export async function loadProjectFiles(paths: string[]): Promise<ProjectFile[]> {
  const files: ProjectFile[] = [];
  for (const path of paths) {
    try {
      const source = await readFile(path, 'utf8');
      const nl = source.indexOf('\n');
      const lang = detectLanguage(path, nl === -1 ? source : source.slice(0, nl));
      if (lang) files.push({ path, source, lang });
    } catch {
      // unreadable files are reported by the parser stage
    }
  }
  return files;
}

async function parseContext(file: ProjectFile, scanRoot: string): Promise<{ ctx: FileContext; free: () => void } | null> {
  let parser;
  try {
    parser = await getParser(file.lang);
  } catch {
    return null; // grammar unavailable: reported by the parse stage
  }
  const text = file.source.charCodeAt(0) === 0xfeff ? file.source.slice(1) : file.source;
  const tree = parseTolerant(parser, text, file.lang);
  if (!tree) return null;
  const root: TSNode = tree.rootNode;
  return {
    ctx: { path: file.path, relPath: relative(scanRoot, file.path).split('\\').join('/'), lang: file.lang, family: LANGUAGE_FAMILY[file.lang], source: text, lines: text.split(/\r?\n/), root },
    free: () => tree.delete(),
  };
}

/** Pattern rules and taint analysis (with cross-file summaries for JS/TS and Python) over a set of files. */
export async function analyzeProject(allFiles: ProjectFile[], options: AnalyzeOptions = {}): Promise<ProjectAnalysis> {
  const factsByFile = new Map<string, FileFacts>();
  const root = options.root ?? process.cwd();
  const skippedMinified: string[] = [];
  const files = allFiles.filter((f) => {
    if (isMinified(f.source) || isVendoredOrGenerated(relative(options.root ?? process.cwd(), f.path).split('\\').join('/'), f.source)) {
      skippedMinified.push(f.path);
      return false;
    }
    return true;
  });
  const findings = new Map<string, RawFinding[]>();
  const timedOut: string[] = [];
  const failed: string[] = [];
  const families = new Set<string>();
  const paths = new Set(files.map((f) => f.path));
  const byTail = tailIndex(paths);
  const global = new Map<string, FnSummary>();
  const importsOf = new Map<string, ReturnType<typeof parseImports>>();

  // Round 1: pattern rules, local taint summaries.
  for (const file of files) {
    const basePack = packFor(LANGUAGE_FAMILY[file.lang]);
    if (!basePack) continue;
    const pack = extendPack(basePack, options.skills?.extras.get(basePack.family));
    families.add(pack.family);
    const parsed = await parseContext(file, root);
    if (!parsed) continue;
    const started = Date.now();
    try {
      const out: RawFinding[] = [...runPatternRules(parsed.ctx, pack)];
      if (Date.now() - started > STAGE_BUDGET_MS) {
        timedOut.push(file.path);
        findings.set(file.path, out);
        continue;
      }
      const nodes = allNodes(parsed.ctx.root);
      // Investigation walks every function's subtree; absurdly nested input would make that quadratic.
      const functionCount = nodes.reduce((n, x) => n + (isFunctionNode(x, parsed.ctx.family) ? 1 : 0), 0);
      if (functionCount > 600 || nodes.length > 80000) {
        timedOut.push(file.path);
      } else {
        try {
          factsByFile.set(file.path, collectFacts(parsed.ctx, nodes, options.publicRoutes ?? []));
          out.push(...analyzeLifecycle(parsed.ctx, nodes), ...analyzeIntent(parsed.ctx, nodes));
        } catch {
          failed.push(file.path); // one odd file must not abort the scan
        }
        if (Date.now() - started > STAGE_BUDGET_MS) {
          timedOut.push(file.path);
          findings.set(file.path, out);
          continue;
        }
      }
      const imports = parseImports(pack.family, file.path, parsed.ctx.source, paths, byTail);
      importsOf.set(file.path, imports);
      try {
        const taint = analyzeFileTaint(parsed.ctx, pack, NO_IMPORTS, global, FILE_BUDGET_MS);
        out.push(...taint.findings);
        for (const [key, summary] of taint.summaries) global.set(key, summary);
      } catch (error) {
        if (!(error instanceof AnalysisTimeout)) throw error;
        timedOut.push(file.path);
      }
      findings.set(file.path, out);
    } catch {
      failed.push(file.path);
    } finally {
      parsed.free();
    }
  }

  // Round 2: files with resolved project imports get cross-file flows (twice, so chains of two hops resolve).
  const withImports = files.filter((f) => {
    const i = importsOf.get(f.path);
    return i && (i.named.size > 0 || i.modules.size > 0);
  });
  for (let round = 0; round < 2 && withImports.length > 0; round += 1) {
    for (const file of withImports) {
      const pack = extendPack(packFor(LANGUAGE_FAMILY[file.lang])!, options.skills?.extras.get(LANGUAGE_FAMILY[file.lang]));
      const parsed = await parseContext(file, root);
      if (!parsed) continue;
      try {
        const taint = analyzeFileTaint(parsed.ctx, pack, importsOf.get(file.path)!, global, FILE_BUDGET_MS);
        for (const [key, summary] of taint.summaries) global.set(key, summary);
        if (round === 1) {
          const previous = (findings.get(file.path) ?? []).filter((f) => f.source !== 'athena-taint');
          findings.set(file.path, [...previous, ...taint.findings]);
        }
      } catch (error) {
        if (error instanceof AnalysisTimeout) {
          if (!timedOut.includes(file.path)) timedOut.push(file.path);
        } else {
          failed.push(file.path);
        }
      } finally {
        parsed.free();
      }
    }
  }

  // Investigation: conventions across files, then offline verification of every candidate.
  const factList = [...factsByFile.values()];
  const map = buildCodebaseMap(factList);
  for (const f of mineConventions(factList)) {
    const { file, ...raw } = f;
    findings.set(file, [...(findings.get(file) ?? []), raw]);
  }
  for (const [path, list] of findings) {
    const seen = new Set<string>();
    const unique = list.filter((f) => {
      const key = `${f.ruleId}:${f.line}:${f.source}`;
      if (seen.has(key)) return false;
      seen.add(key);
      return true;
    });
    findings.set(path, unique.map((raw) => ({ ...raw, ...verifyFinding(path, raw, map, factsByFile.get(path), options.skills?.metaById) })));
  }
  return { findings, timedOut: [...new Set(timedOut)], failed, families, skippedMinified, map, facts: factsByFile };
}
